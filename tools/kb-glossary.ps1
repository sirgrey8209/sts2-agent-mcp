<#
.SYNOPSIS
    Aligns knowledge-base documents with the game's own names.
    - Appends (or regenerates) a "Glossary (game names)" section listing every backticked class id in the document
      that maps to a power, card, relic, potion, enchantment, affliction or monster, with its in-game name.
    - Lists single-word names written directly before an id that differ from the game name,
      e.g. "WRONG(`WeakPower`)"; with -FixNames they are replaced by "GAME_NAME(`WeakPower`)".
      The word may be prose rather than a name ("...if killed(`HeistPower`)", "perfect fit(`PerfectFit`)"), so review the
      listed pairs before/after -FixNames. Words with verb/conjunction endings are never replaced. Particles after the id
      are not adjusted.

.EXAMPLE
    .\kb-glossary.ps1 -Loc C:\WorkSpace\sts2-decompiled\loc\v0.107.1            # glossary + list mismatches
    .\kb-glossary.ps1 -Loc C:\WorkSpace\sts2-decompiled\loc\v0.107.1 -FixNames  # also replace them
#>
param([Parameter(Mandatory = $true)][string]$Loc, [switch]$FixNames)

$ErrorActionPreference = "Stop"
. (Join-Path $PSScriptRoot "kb-common.ps1")
$kb = Join-Path (Split-Path $PSScriptRoot -Parent) "kb"
$hangul = '\uAC00-\uD7A3'
$marker = '<!-- glossary: generated by tools/kb-glossary.ps1 -->'

# entry -> (kind, game name)
$names = @{}
$tables = @(
    @{ Table = "powers"; Key = "title"; Kind = "power" }, @{ Table = "cards"; Key = "title"; Kind = "card" },
    @{ Table = "relics"; Key = "title"; Kind = "relic" }, @{ Table = "potions"; Key = "title"; Kind = "potion" },
    @{ Table = "enchantments"; Key = "title"; Kind = "enchantment" }, @{ Table = "afflictions"; Key = "title"; Kind = "affliction" },
    @{ Table = "monsters"; Key = "name"; Kind = "monster" })
foreach ($t in $tables) {
    $json = [System.IO.File]::ReadAllText((Join-Path $Loc "loc-$($t.Table).json"), [System.Text.Encoding]::UTF8) | ConvertFrom-Json
    foreach ($p in $json.PSObject.Properties) {
        if ($p.Name -match "^(?<e>[A-Z0-9_]+)\.$($t.Key)$" -and -not $names.ContainsKey($Matches['e'])) {
            $clean = [regex]::Replace([string]$p.Value, '\[[^\]]*\]', '').Trim()
            if ($clean) { $names[$Matches['e']] = @{ Kind = $t.Kind; Name = $clean } }
        }
    }
}

$fixed = 0
$docs = Get-ChildItem $kb -Recurse -Filter *.md | Where-Object { $_.Name -ne "README.md" }
foreach ($f in $docs) {
    $text = [System.IO.File]::ReadAllText($f.FullName, [System.Text.Encoding]::UTF8)
    $cut = $text.IndexOf($marker)
    if ($cut -ge 0) { $text = $text.Substring(0, $cut).TrimEnd() + "`n" }

    $found = [ordered]@{}
    foreach ($m in [regex]::Matches($text, '`([A-Z][A-Za-z0-9]+)`')) {
        $id = $m.Groups[1].Value
        $entry = Get-ModelEntry $id
        if (-not $names.ContainsKey($entry)) {
            # Power ids are often written without the Power suffix.
            if ($names.ContainsKey("$($entry)_POWER")) { $entry = "$($entry)_POWER" } else { continue }
        }
        if (-not $found.Contains($id)) { $found[$id] = $names[$entry] }
    }

    foreach ($id in @($found.Keys)) {
        $game = $found[$id].Name
        if ($game -match '\s') { continue }
        $pattern = "(?<![$hangul])(?<word>[$hangul]+)\s?\(``$([regex]::Escape($id))``\)"
        $text = [regex]::Replace($text, $pattern, {
            param($m)
            $word = $m.Groups['word'].Value
            if ($word -eq $game) { return $m.Value }
            # Endings that mark prose, not a name: -myeon, -si, -da, -go, -myeo, -seo, -gi, -ge, -hi.
            $prose = $word -match '[면시다고며서기게히]$'
            $what = if ($FixNames -and -not $prose) { "fixed" } elseif ($prose) { "skip " } else { "diff " }
            Write-Host "$what $($f.Name): $word -> $game (``$id``)"
            if ($what -ne "fixed") { return $m.Value }
            $script:fixed++
            return "$game(``$id``)"
        })
    }

    if ($found.Count -gt 0) {
        $lines = $found.Keys | ForEach-Object { "- ``$_``: $($found[$_].Name) ($($found[$_].Kind))" }
        $text = $text.TrimEnd() + "`n`n" + $marker + "`n## Glossary (game names)`n" + ($lines -join "`n") + "`n"
    }
    [System.IO.File]::WriteAllText($f.FullName, $text, $script:Utf8)
}
Write-Host "processed $($docs.Count) document(s), fixed $fixed inline name(s)"
